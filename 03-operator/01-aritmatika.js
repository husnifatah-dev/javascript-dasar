let a = 10;
let b = 5;

console.log("==== OPERASI DASAR ===");
console.log("Penjumlahan (10 + 5) :", a + b); // 15
console.log("Pengurangan (10 - 5) :", a - b); // 5
console.log("Perkalian (10 * 5) :", a * b); // 50
console.log("Pembagian (10 / 5) :", a / b); // 2
console.log("Modulus/Sisa Bagi (10 % 5) :", a % b); // 0
console.log("Eksponen/Pangkat (10 ** 5) :", a ** b); // 100.000

console.log("\n===Increment & Decrement===");
let nilai = 5;
nilai++; //nilai akan ditambah 1
console.log("Setelah increment :", nilai); // 6

nilai--; //nilai akan dikurangi 1
console.log("Setelah decrement :", nilai); // 5, karena value dari nilai terkahir sudah menalami perubahan di increment jadi setelah decrement jadinya 5.

