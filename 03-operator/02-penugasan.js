let saldo = 100000;
console.log("Saldo awal:", saldo); // 100000

// menambah saldo bisa menggunakan += sama aja kaya (saldo = saldo + 50000)
saldo += 50000;
console.log("Setelah deposit (+= 50000):", saldo); //150000

// mengurangi saldo (salso = saldo - 20000)
saldo -= 20000;
console.log("Setelah penarikan (-=20000):", saldo); // 130000

// mengalikan nilai
let poin = 10;
poin *= 2;
console.log("Poin dikali 2 (*=):", poin); // 20

// Pembagian 
poin /= 4;
console.log("Poin dibagi 4 (/=4):", poin); // 5